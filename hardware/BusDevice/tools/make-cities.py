"""Generate the ESP32 MyBus catalogue from the app's CityCatalog."""
import json
from pathlib import Path
import re

sketch = Path(__file__).resolve().parents[1]
app = sketch.parents[1] / "app/src/main/java/pl/walbrzych/autobus/data/CityConfig.kt"
entries = re.findall(r'CityConfig\((\d+), "([^"]+)", "[^"]+", "(https?://[^"]+)", "([^"]+)"\)', app.read_text())
assert len(entries) > 40 and any(row[0] == "10" for row in entries)
assert len({row[0] for row in entries}) == len(entries)
lines = ["// Generated by tools/make-cities.py from CityCatalog.\n#pragma once\n", "static constexpr BusCity busCities[] = {"]
for city_id, name, base, code in entries:
    strings = ', '.join(json.dumps(s, ensure_ascii=False) for s in (name, base.rstrip('/') + '/'))
    lines.append(f"  {{{city_id}, {strings}, {sum(map(ord, code))}}},")
lines.append("};")
(sketch / "src/generated/BusCities.h").write_text("\n".join(lines) + "\n")
