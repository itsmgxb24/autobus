from pathlib import Path
import sys
from PIL import Image, ImageDraw, ImageFont

regular, bold = sys.argv[1:3]
characters = "".join(chr(i) for i in range(32, 127)) + "ĄĆĘŁŃÓŚŹŻąćęłńóśźż–—·…"
out = ["// Inter bitmap glyphs. Generated by tools/make-fonts.py.", "#pragma once"]
out.append("static constexpr uint16_t extraGlyphs[] = {" + ", ".join(str(ord(c)) for c in characters[95:]) + "};")

for font_name, path, size in [("caption", bold, 10), ("body", regular, 14), ("time", bold, 17), ("title", bold, 24)]:
    font = ImageFont.truetype(path, size)
    metadata, pixels = [], []
    for character in characters:
        left, top, right, bottom = font.getbbox(character, anchor="ls")
        width, height = right-left, bottom-top
        metadata.append((len(pixels), width, height, round(font.getlength(character)), left, top))
        image = Image.new("L", (max(width, 1), max(height, 1)))
        ImageDraw.Draw(image).text((-left, -top), character, font=font, fill=255, anchor="ls")
        bits = [image.getpixel((x, y)) >= 120 for y in range(height) for x in range(width)]
        bits.extend([False] * ((-len(bits)) % 8))
        pixels += [sum(b << (7-k) for k, b in enumerate(bits[i:i+8])) for i in range(0,len(bits),8)]
    out += [f"static constexpr Glyph {font_name}Glyphs[] = {{"]
    out += ["  {" + ", ".join(str(v) for v in glyph) + "}," for glyph in metadata]
    out += ["};", f"static constexpr uint8_t {font_name}Pixels[] = {{"]
    out += ["  " + ", ".join(f"0x{n:02x}" for n in pixels[i:i+16]) + "," for i in range(0,len(pixels),16)]
    out += ["};", f"static constexpr Font {font_name}Font = {{{font_name}Glyphs, {font_name}Pixels}};"]

output = Path(__file__).resolve().parents[1] / "src/generated/InterBitmaps.h"
output.write_text("\n".join(out) + "\n")
